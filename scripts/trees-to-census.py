#!/usr/bin/env python3
"""Turn a tgctree CSV export into app/src/data/treeCensus.ts.

Usage: python3 -I scripts/trees-to-census.py ~/Downloads/demo-trees-YYYY-MM-DD.csv
"""
import csv, json, math, sys, collections
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'app/src/data/treeCensus.ts'

# CSV speciesId -> species.ts id (synonyms and site-specific ids)
ALIAS = {
    'phyllanthus-emblica': 'amla',
    'elaeocarpus-sphaericus': 'elaeocarpus-ganitrus',
    'other-other': 'other',
}
# Free-text names entered under "other"
OTHER_NAMES = {
    'white lead tree': 'leucaena-leucocephala',
    'gulhomar': 'delonix-regia',
    'solanum indicum': 'solanum-indicum',
}
UNIDENTIFIED = 'other'


def species_id(r):
    sid = ALIAS.get(r['speciesId'], r['speciesId'])
    if sid == 'other':
        sid = OTHER_NAMES.get(r['speciesScientific'].strip().lower(), 'other')
    return sid


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


rows = [r for r in csv.DictReader(open(sys.argv[1], encoding='utf-8-sig')) if r['status'] == 'alive']
count = collections.Counter()
co2 = collections.defaultdict(float)
agb = 0.0
largest = None
for r in rows:
    sid = species_id(r)
    count[sid] += 1
    co2[sid] += num(r['co2eKg'])
    agb += num(r['agbKg'])
    if largest is None or num(r['co2eKg']) > num(largest['co2eKg']):
        largest = r

named = {k: v for k, v in count.items() if k != UNIDENTIFIED}
n = sum(named.values())
shannon = -sum(c / n * math.log(c / n) for c in named.values())
simpson = 1 - sum(c * (c - 1) for c in named.values()) / (n * (n - 1))
dates = sorted(r['surveyDate'][:10] for r in rows if r['surveyDate'])
total_co2 = sum(co2.values())

data = {
    'source': Path(sys.argv[1]).name,
    'surveyFrom': dates[0],
    'surveyTo': dates[-1],
    'totalTrees': len(rows),
    'unidentified': count.get(UNIDENTIFIED, 0),
    'totalSpecies': len(named),
    'totalCo2eKg': round(total_co2),
    'carbonKg': round(total_co2 / 3.67),
    'agbKg': round(agb),
    'shannon': round(shannon, 2),
    'simpson': round(simpson, 2),
    'largestTree': {'tag': largest['treeNumber'], 'speciesId': species_id(largest), 'co2eKg': round(num(largest['co2eKg']))},
    'bySpecies': {k: {'count': count[k], 'co2eKg': round(co2[k])} for k, _ in count.most_common()},
}

OUT.write_text(
    '// GENERATED by scripts/trees-to-census.py from the tgctree CSV export. Do not edit by hand.\n'
    f'export const treeCensus = {json.dumps(data, indent=2, ensure_ascii=False)} as const\n'
)
print(f"{len(rows)} trees, {len(named)} species, {total_co2/1000:.1f} t CO2e, H'={shannon:.2f}, 1-D={simpson:.2f} -> {OUT}")
